package com.smartshipment.shipment.dto;

import java.math.BigDecimal;
import java.time.Instant;
import jakarta.validation.constraints.*;

public record ShipmentRequest(
        @NotNull @Positive Long customerId,
        @Null(message = "Tracking number is generated by the server") String trackingNumber,
        @NotBlank @Size(max = 160) String recipientName,
        @NotBlank @Size(max = 255) String deliveryAddress,
        @NotNull @DecimalMin(value = "0", inclusive = false) @Digits(integer = 10, fraction = 2) BigDecimal weightKg,
        @NotNull @Future Instant expectedDeliveryAt) {
}
