-- The trips table must already exist.
BEGIN;

CREATE TABLE public.employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    employee_number VARCHAR(30) NOT NULL UNIQUE,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE public.trip_employees (
    trip_id BIGINT NOT NULL,
    employee_id BIGINT NOT NULL,
    PRIMARY KEY (trip_id, employee_id),
    CONSTRAINT fk_trip_employees_trip FOREIGN KEY (trip_id) REFERENCES public.trips (id),
    CONSTRAINT fk_trip_employees_employee FOREIGN KEY (employee_id) REFERENCES public.employees (id)
);

CREATE INDEX idx_trip_employees_employee ON public.trip_employees (employee_id);

COMMIT;
