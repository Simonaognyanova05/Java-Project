-- Minimal shipment model for transport assignment; lifecycle/history added separately.
CREATE TABLE public.shipments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_number VARCHAR(36) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES public.customers(id),
    trip_id BIGINT REFERENCES public.trips(id),
    status VARCHAR(20) NOT NULL,
    weight_kg NUMERIC(12, 2) NOT NULL CHECK (weight_kg > 0),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT,
    CONSTRAINT shipments_status_valid CHECK (status IN ('CREATED', 'ACCEPTED', 'LOADED', 'IN_TRANSIT', 'DELIVERED'))
);
CREATE INDEX idx_shipments_trip ON public.shipments(trip_id);
