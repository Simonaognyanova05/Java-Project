-- Run once against smart_shipment_tracking before restarting the application.
CREATE TABLE trips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origin VARCHAR(255) NOT NULL,
    destination VARCHAR(255) NOT NULL,
    departure_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expected_arrival_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version BIGINT,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT trips_schedule_valid CHECK (departure_at < expected_arrival_at)
);
