-- Run once against smart_shipment_tracking before restarting the application.
CREATE TABLE public.tracking_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL REFERENCES public.shipments(id),
    previous_status VARCHAR(20),
    new_status VARCHAR(20) NOT NULL,
    occurred_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    employee_id BIGINT REFERENCES public.employees(id),
    CONSTRAINT tracking_events_new_status_valid
        CHECK (new_status IN ('CREATED', 'ACCEPTED', 'LOADED', 'IN_TRANSIT', 'DELIVERED')),
    CONSTRAINT tracking_events_previous_status_valid
        CHECK (previous_status IS NULL OR previous_status IN ('CREATED', 'ACCEPTED', 'LOADED', 'IN_TRANSIT', 'DELIVERED')),
    CONSTRAINT tracking_events_actor_required
        CHECK (new_status = 'CREATED' OR employee_id IS NOT NULL),
    CONSTRAINT tracking_events_previous_required
        CHECK (new_status = 'CREATED' OR previous_status IS NOT NULL)
);
CREATE INDEX idx_tracking_events_shipment
    ON public.tracking_events(shipment_id, occurred_at, id);
